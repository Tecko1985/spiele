function erzeugeVereineDeck() {
  return VEREINE_DATEN.map((eintrag, i) => {
    const [
      name, ligaLand, kaderwert, meistertitel, pokaltitel, europapokal,
      stadionkapazitaet, mitglieder, vereinsalter, nationalspieler
    ] = eintrag;
    return {
      id: `verein-${i + 1}`,
      name,
      rolle: ligaLand,
      foto: null,
      avatarFarbe: AVATAR_FARBEN_POOL[i % AVATAR_FARBEN_POOL.length],
      eigenschaften: {
        kaderwert,
        meistertitel,
        pokaltitel,
        europapokal,
        stadionkapazitaet,
        mitglieder,
        vereinsalter,
        nationalspieler
      }
    };
  });
}

